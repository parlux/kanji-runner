import data from "../data/loanwords.json";
import kanjiWordData from "../data/words.json";
import { KANJI, maxLevel } from "./kanji";
import { itemKey, LEARNED_BOX } from "./srs";
import { WORDS_PER_LEVEL } from "./tuning";
import type { Progress, WordItem } from "./types";

/** One entry of `loanwords.json`, before its level is assigned. */
export type LoanwordEntry = { word: string; glosses: string[] };

/** Entry i joins kanji level 2 + floor(i / WORDS_PER_LEVEL), capped at `lastLevel`. */
export function assignLevels(
  entries: readonly LoanwordEntry[],
  lastLevel: number,
): WordItem[] {
  return entries.map((e, i) => ({
    word: e.word,
    kind: "loanword" as const,
    glosses: e.glosses,
    level: Math.min(2 + Math.floor(i / WORDS_PER_LEVEL), lastLevel),
  }));
}

/** One entry of `words.json` (generated by `npm run data:build`). */
export type KanjiWordEntry = {
  word: string;
  reading: string;
  glosses: string[];
  kind: "single" | "okurigana" | "compound";
  level: number;
};

/** Loanwords first, then kanji words, each in its own order. */
export const WORDS: WordItem[] = [
  ...assignLevels(data as LoanwordEntry[], maxLevel(KANJI)),
  ...(kanjiWordData as KanjiWordEntry[]),
];

/** A kanji word has a reading gate; a loanword does not. */
export const isKanjiWord = (w: WordItem): boolean => w.kind !== "loanword";

const FULL_SIZE: Record<string, string> = {
  ァ: "ア",
  ィ: "イ",
  ゥ: "ウ",
  ェ: "エ",
  ォ: "オ",
  ッ: "ツ",
  ャ: "ヤ",
  ュ: "ユ",
  ョ: "ヨ",
};

/** The kana a word needs learned: ー dropped, small kana as full size, each once in order. */
export function kanaNeeded(word: string): string[] {
  const chars = [...word]
    .filter((c) => c !== "ー")
    .map((c) => FULL_SIZE[c] ?? c);
  return [...new Set(chars)];
}

const isKanji = (c: string): boolean => /[\u4e00-\u9fff]/.test(c);

/** The kanji a word needs learned: its kanji characters, 々 dropped, each once in order. */
export function kanjiNeeded(word: string): string[] {
  const chars = [...word].filter((c) => isKanji(c));
  return [...new Set(chars)];
}

/**
 * A word may be asked once its level is unlocked and what it needs is learned:
 * every kana of a loanword, the meaning of every kanji of a kanji word (box ≥ 2).
 */
export function isWordEligible(word: WordItem, progress: Progress): boolean {
  const needs =
    word.kind === "loanword"
      ? kanaNeeded(word.word).map((c) => itemKey(c, "kana"))
      : kanjiNeeded(word.word).map((c) => itemKey(c, "meaning"));
  return (
    word.level <= progress.unlockedLevel &&
    needs.every((k) => (progress.items[k]?.box ?? 0) >= LEARNED_BOX)
  );
}
